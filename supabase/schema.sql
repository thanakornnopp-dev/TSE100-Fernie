-- 1. สร้างตารางบันทึกข้อมูล Telemetry จากโหนดเสาไฟ
CREATE TABLE IF NOT EXISTS public.telemetry_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT timezone('asia/bangkok', now()) NOT NULL,
    node_id TEXT DEFAULT 'NODE-GYM7-01' NOT NULL,
    traffic_count INTEGER DEFAULT 0 NOT NULL,
    light_status TEXT DEFAULT 'STANDBY' NOT NULL,
    power_watts NUMERIC(4, 1) DEFAULT 0.6 NOT NULL,
    alert_status TEXT DEFAULT 'NORMAL' NOT NULL
);

-- 2. สร้าง Index เพื่อให้การดึงข้อมูลย้อนหลังรวดเร็วระดับ Microseconds
CREATE INDEX IF NOT EXISTS idx_telemetry_created_at ON public.telemetry_logs (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_telemetry_node_id ON public.telemetry_logs (node_id);

-- 3. เปิดใช้งาน Row Level Security (RLS) เพื่อความปลอดภัย
ALTER TABLE public.telemetry_logs ENABLE ROW LEVEL SECURITY;

-- นโยบายที่ 1: อนุญาตให้ใครก็ได้อ่านข้อมูล (สำหรับหน้าเว็บ Dashboard)
CREATE POLICY "Allow public read access" 
ON public.telemetry_logs 
FOR SELECT 
USING (true);

-- นโยบายที่ 2: อนุญาตให้ ESP32 บันทึกข้อมูลเข้ามาได้ (ผ่าน Anon Key)
CREATE POLICY "Allow anon insert access" 
ON public.telemetry_logs 
FOR INSERT 
WITH CHECK (true);

-- 4. เปิดใช้งาน Realtime Publication (หัวใจสำคัญที่ทำให้หน้าเว็บอัปเดตสดแบบ WebSockets)
ALTER PUBLICATION supabase_realtime ADD TABLE public.telemetry_logs;

